const assert=require('node:assert/strict');
const XLSX=require('../lib/xlsx.full.min.js');
const cleaner=require('../tagihan-cleaner.js');
const headers=cleaner.columns.map(([,source])=>source);
function workbook(rows,head=headers){const wb=XLSX.utils.book_new();XLSX.utils.book_append_sheet(wb,XLSX.utils.aoa_to_sheet([[],[],head,...rows]),'Detail1');return wb;}
function row(account,kol,jt){return ['13112A',123,'Petugas',account,'KUR','Contoh',100,98.1234,kol,1,46000,jt,null,1200000,735980.49,234,0];}
const source=[row(111,'2A',10),row(112,1,10),row(113,1,2),row(114,'2A',2),row(115,1,2)];
const result=cleaner.convert(workbook(source),XLSX);
const saved=XLSX.read(XLSX.write(result.workbook,{type:'buffer',bookType:'xlsx'}),{type:'buffer'});
const values=XLSX.utils.sheet_to_json(saved.Sheets.ALL,{header:1,defval:null});
assert.equal(result.count,5);
assert.equal(JSON.stringify(values[2]),JSON.stringify(cleaner.columns.map(([name])=>name)));
assert.equal(JSON.stringify(values.slice(3).map(r=>r[3])),JSON.stringify([113,115,112,114,111]));
const byAccount=new Map(source.map(r=>[r[3],r]));
for(const actual of values.slice(3))assert.equal(JSON.stringify(actual),JSON.stringify(byAccount.get(actual[3])));
assert.equal(result.workbook.Sheets.ALL['!cols'][6].hidden,false);
assert.equal(result.workbook.Sheets.ALL.G4.v,100);
assert.equal(result.workbook.Sheets.ALL.Q4.v,0);
assert.equal(result.workbook.Sheets.ALL.M4,undefined);
assert.throws(()=>cleaner.convert(workbook(source,headers.slice(1)),XLSX),/Header/);
assert.throws(()=>cleaner.convert(workbook(source,[...headers,'acctno']),XLSX),/duplikat/);
assert.throws(()=>cleaner.convert(workbook([row(null,1,2)]),XLSX),/rekening kosong/);
const shuffled=headers.map((h,i)=>[h,i]).reverse();
const reordered=cleaner.convert(workbook(source.map(r=>shuffled.map(([,i])=>r[i])),shuffled.map(([h])=>h)),XLSX);
assert.equal(JSON.stringify(XLSX.utils.sheet_to_json(reordered.workbook.Sheets.ALL,{header:1})),JSON.stringify(XLSX.utils.sheet_to_json(result.workbook.Sheets.ALL,{header:1})));
const formulaSource=workbook(source);formulaSource.Sheets.Detail1.O4.f='9999999-1';
const formulaResult=cleaner.convert(formulaSource,XLSX);
assert.equal(Object.values(formulaResult.workbook.Sheets.ALL).some(c=>c?.f),false);
assert.equal(cleaner.compare('2C',3)<0,true);
const expanded=workbook(source.map((r,i)=>[...r,i?'Bandung Rancaekek 2':'Bandung Rancaekek 1',46321,0]),[...headers,'mbu','posisi','kolom tambahan']);
const prepared=cleaner.prepare(expanded,XLSX);
assert.equal(prepared.branches.length,1);
assert.equal(prepared.branches[0].count,source.length);
assert.equal(prepared.reportDate,'2026-10-26');
const hiddenResult=cleaner.convertPrepared(prepared,XLSX,['13112A']);
assert.equal(hiddenResult.headers.length,20);
assert.equal(hiddenResult.workbook.Sheets.ALL['!cols'][17].hidden,true);
assert.equal(hiddenResult.workbook.Sheets.ALL.T4.v,0);
const metrics=[row(201,1,5),row(202,1,5),row(203,'2A',5),row(204,'2A',5)];
metrics[0][8]=1;metrics[0][7]=10;metrics[1][7]=0;metrics[2][7]=null;metrics[3][7]='teks';
const measured=cleaner.convert(workbook(metrics),XLSX);
assert.equal(measured.pivotSummary.total.total.bade,10);
assert.equal(measured.pivotSummary.total.total.count,3);
assert.equal(measured.workbook.Sheets.Pivot.C9.v,1);
assert.equal(measured.workbook.Sheets.Pivot.D9.v,0);
const zero=row(205,1,5);zero[7]=0;
assert.equal(cleaner.convert(workbook([zero]),XLSX).workbook.Sheets.Pivot.C9.t,'e');
async function checkTable(){
  const JSZip=require('../lib/jszip.min.js');
  const data=await cleaner.write(result,XLSX,JSZip);
  const zip=await JSZip.loadAsync(data);
  const table=await zip.file('xl/tables/table1.xml').async('string');
  assert.ok(table.includes('name="TableStyleMedium9"'));
  assert.ok(table.includes('showRowStripes="1"'));
  assert.ok(table.includes('ref="A3:Q8"'));
  assert.equal((table.match(/<tableColumn /g)||[]).length,17);
  const xml=await zip.file('xl/worksheets/sheet1.xml').async('string');
  assert.ok(xml.includes('<tablePart r:id="rIdTable1"/>'));
  assert.equal(xml.includes('<autoFilter'),false);
  assert.ok((await zip.file('xl/styles.xml').async('string')).includes('<sz val="11"/>'));
  const restored=XLSX.read(data,{type:'array'});
  assert.equal(JSON.stringify(restored.SheetNames),JSON.stringify(['ALL','Pivot']));
  const pivot=await zip.file('xl/pivotTables/pivotTable1.xml').async('string');
  assert.ok(pivot.includes('gridDropZones="1"'));
  assert.ok(pivot.includes('showDropZones="1"'));
  assert.ok(pivot.includes('compact="0"'));
  assert.ok(pivot.includes('dataOnRows="1"'));
  assert.ok(pivot.includes('<rowFields count="2"><field x="2"/><field x="-2"/></rowFields>'));
  assert.ok(pivot.includes('<pageFields count="2"><pageField fld="0"/><pageField fld="4"/></pageFields>'));
  assert.ok(pivot.includes('<colFields count="1"><field x="8"/></colFields>'));
  assert.ok(pivot.includes('name=".jumlahrek" fld="7" subtotal="count"'));
  assert.ok(pivot.includes('name=".%kol" fld="7" subtotal="sum" showDataAs="percentOfRow"'));
  assert.equal((pivot.match(/<pivotField /g)||[]).length,17);
  const cache=await zip.file('xl/pivotCache/pivotCacheDefinition1.xml').async('string');
  assert.ok(cache.includes('recordCount="5"'));
  assert.ok(cache.includes('<worksheetSource name="Table1" sheet="ALL"/>'));
  assert.equal((cache.match(/<cacheField /g)||[]).length,17);
  const records=await zip.file('xl/pivotCache/pivotCacheRecords1.xml').async('string');
  assert.equal((records.match(/<r>/g)||[]).length,5);
  assert.equal(JSON.stringify(XLSX.utils.sheet_to_json(restored.Sheets.ALL,{header:1,defval:null})),JSON.stringify(values));
  console.log('Tagihan cleaner: raw values, sorting, hidden columns, native blue table and classic Pivot/cache export passed.');
}
checkTable().catch(error=>{console.error(error);process.exitCode=1;});
